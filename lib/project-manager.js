/**
 * 某个专家 id 对应的专家小组长建议名字（异步结算通知里用来点名）。
 *
 * 名册可自定义：不在六位预置专家里时按 `<id>-lead` 生成一个可读名字。
 *
 * @param {string} specialistId - 专家 id（例如 `architect`）。
 * @returns {string} 小组长名字（例如 `architect-lead`）。
 */
export function leaderNameForSpecialist(specialistId) {
  const known = PIPELINE_SPECIALISTS.find((entry) => entry.id === specialistId);
  if (known !== undefined) return known.lead;
  return `${String(specialistId)}-lead`;
}

