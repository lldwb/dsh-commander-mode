"""
session-summary 技能自测：逐项验证 extract-session.py 的抽取模式、过滤规则、
会话定位与退出码分支。

**改过 `scripts/extract-session.py` 必须重跑本脚本**。其中两条用例锚定历史回归
（曾因实际使用暴露并修复的缺陷，防止复发）：
  C02 ← c788e2b（--user 模式漏抽技能命令发起的用户输入）
  C11 ← db6bd0f（timeline 模式斜杠命令用户消息被整条丢弃）

隔离性：全部用例在系统临时目录里构造**合成**会话记录（.jsonl），不读取也不触碰
真实会话；定位类用例（C13）通过临时 HOME / USERPROFILE 指向假 projects 目录，
不依赖本机真实 `~/.claude/projects`。

用法:
    python selftest.py        # 跑全部用例，逐项打印 PASS / FAIL / ERROR
退出码: 0 = 无 FAIL / ERROR；1 = 有失败项
"""
