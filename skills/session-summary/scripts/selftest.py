def main():
    print("session-summary 自测：%d 个用例" % len(RESULTS))
    fail = 0
    for fn in RESULTS:
        name = fn.__name__
        try:
            fn()
            print("PASS  %s" % name)
        except AssertionError as e:
            fail += 1
            print("FAIL  %s —— %s" % (name, e))
        except Exception:
            fail += 1
            print("ERROR %s\n%s" % (name, traceback.format_exc()))
    print("\n结果: %d/%d 通过" % (len(RESULTS) - fail, len(RESULTS)))
    return 1 if fail else 0


if __name__ == "__main__":
    sys.exit(main())
