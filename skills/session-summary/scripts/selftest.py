# Windows 控制台缺省 GBK，强制 UTF-8 输出（同仓库其他脚本的处理）。
def _ensure_utf8():
    for name in ("stdout", "stderr"):
        stream = getattr(sys, name, None)
        if stream is None:
            continue
        try:
            stream.reconfigure(encoding="utf-8", errors="backslashreplace")
            continue
        except Exception:
            pass
        try:
            buf = getattr(stream, "buffer", None)
            if buf is not None and hasattr(stream, "write"):
                setattr(sys, name, codecs.getwriter("utf-8")(buf, errors="backslashreplace"))
        except Exception:
            pass


_ensure_utf8()

# 自定位被测脚本（技能目录自包含，不依赖仓库位置与盘符）。
HERE = os.path.dirname(os.path.abspath(__file__))
EXE = os.path.join(HERE, "extract-session.py")
PY = sys.executable

RESULTS = []


def run(args, cwd=None, home=None):
    """跑被测脚本；home 时把 HOME / USERPROFILE 一并指向假主目录（定位类用例）。"""
    env = dict(os.environ)
    if home:
        env["HOME"] = home
        env["USERPROFILE"] = home
    return subprocess.run([PY, EXE] + list(args), cwd=cwd, capture_output=True,
                          encoding="utf-8", errors="replace", env=env)


def urec(text=None, ts="2026-09-22T10:00:00.000Z", meta=False, content=None):
    """合成 user 记录：content 缺省为纯文本；给 list 时按原样塞进 message.content。"""
    rec = {"type": "user", "timestamp": ts, "message": {"role": "user",
            "content": content if content is not None else text}}
    if meta:
        rec["isMeta"] = True
    return rec


def arec(blocks=None, ts="2026-09-22T10:00:01.000Z", sidechain=False):
    """合成 assistant 记录：blocks 为 content 列表（text / thinking / tool_use）。"""
    rec = {"type": "assistant", "timestamp": ts,
           "message": {"role": "assistant", "content": blocks or []}}
    if sidechain:
        rec["isSidechain"] = True
    return rec


def write_session(records, d, name="s.jsonl"):
    path = os.path.join(d, name)
    with open(path, "w", encoding="utf-8") as f:
        for r in records:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    return path


def check(cond, msg):
    if not cond:
        raise AssertionError(msg)


def wrap_case(fn):
    RESULTS.append(fn)
    return fn


@wrap_case
def C01_user基础抽取():
    d = tempfile.mkdtemp(prefix="ss-")
    try:
        p = write_session([urec("第一句用户输入"), urec("第二句用户输入", ts="2026-09-22T11:00:00.000Z")], d)
        r = run([p, "--user", "--stdout"])
        check(r.returncode == 0, "退出码 %s" % r.returncode)
        check("第一句用户输入" in r.stdout and "第二句用户输入" in r.stdout, "两条消息未都抽出: %s" % r.stdout)
        check("### 2026-09-22T11:00:00.000Z" in r.stdout, "时间戳未按原样输出")
        check("[user] 2 条用户消息" in r.stdout, "统计行缺失: %s" % r.stdout)
    finally:
        shutil.rmtree(d, ignore_errors=True)


